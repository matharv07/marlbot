#!/usr/bin/env python3
"""
export_continuous_world.py — Continuous Arena Exporter for Pacmanbot Gazebo / MuJoCo Simulation.

Directly bridges pacmanbot.world.World into Gazebo SDF and MuJoCo MJCF, rigorously
accounting for the physical dimensions of the SvanM2 quadruped:
  • SvanM2 length: 0.66 m, width: 0.56 m, stance sweep: 0.43 m
  • Dynamic trotting clearance radius: ~0.50 - 0.55 m
  • Scale factor S = 1.5 m / unit yields corridor widths of 1.8 - 2.8 m
  • Wall height: 0.75 m
  • Hovering contactless pellets at z = 0.36 m (regular) and z = 0.38 m (power)
"""

import sys
import os
import json
import math
import argparse
import numpy as np

# Ensure pacmanbot is in path
_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_PACMANBOT_DIR = os.path.join(_REPO_ROOT, "pacmanbot")
if _PACMANBOT_DIR not in sys.path:
    sys.path.insert(0, _PACMANBOT_DIR)

from world import World, Capsule, CurvedWall
from curriculum import STAGES


def liang_barsky_clip(x1, y1, x2, y2, xmin, xmax, ymin, ymax):
    """Clips a 2D line segment (x1, y1) -> (x2, y2) to the rectangle [xmin, xmax] x [ymin, ymax]."""
    dx = x2 - x1
    dy = y2 - y1
    p = [-dx, dx, -dy, dy]
    q = [x1 - xmin, xmax - x1, y1 - ymin, ymax - y1]
    u1 = 0.0
    u2 = 1.0
    for pi, qi in zip(p, q):
        if pi == 0:
            if qi < 0:
                return None
        else:
            t = qi / pi
            if pi < 0:
                if t > u2:
                    return None
                if t > u1:
                    u1 = t
            else:
                if t < u1:
                    return None
                if t < u2:
                    u2 = t
    if u1 > u2:
        return None
    cx1 = x1 + u1 * dx
    cy1 = y1 + u1 * dy
    cx2 = x1 + u2 * dx
    cy2 = y1 + u2 * dy
    if (cx2 - cx1)**2 + (cy2 - cy1)**2 < 0.04:  # Drop degenerate micro-segments < 0.2 units
        return None
    return cx1, cy1, cx2, cy2


def generate_and_export(stage_idx: int = 1,
                        scale: float = 1.5,
                        wall_height: float = 0.75,
                        out_dir: str = None,
                        seed: int = 42):
    if out_dir is None:
        out_dir = os.path.join(_REPO_ROOT, "pacman_sim", "worlds")
    os.makedirs(out_dir, exist_ok=True)

    np.random.seed(seed)
    import random
    random.seed(seed)

    stage = STAGES[min(stage_idx, len(STAGES) - 1)]
    width = stage.cols
    height = stage.rows
    n_power = stage.n_power
    n_ghosts = stage.n_ghosts

    print(f"=== Generating Continuous Arena (Stage {stage_idx}) ===")
    print(f"  Grid Units: {width} x {height}, N_Ghosts: {n_ghosts}, N_Power: {n_power}")
    print(f"  Scale Factor: {scale:.2f} m/unit -> World Extent: {width*scale:.1f} m x {height*scale:.1f} m")

    w = World(width, height, resolution=0.5)
    w.generate(n_obstacles=25, complexity=2, n_power=n_power)
    w.generate_roadmap(n_samples=150)

    # Origin offset to center arena at (0, 0) in world coordinates
    x_offset = (width / 2.0)
    y_offset = (height / 2.0)

    def to_world(px, py):
        return (float(px - x_offset) * scale, float(py - y_offset) * scale)


    # Extract all capsule segments:
    # w.obstacles[:4] are the 4 perimeter walls [0, 0] -> [width, height]
    # w.obstacles[4:] are internal obstacles generated by random walks that can wander outside bounds.
    # We clip all internal obstacles strictly inside the perimeter box so no elements poke out.
    boundary_caps = []
    internal_caps = []
    for idx, obs in enumerate(w.obstacles):
        sub_caps = [obs] if isinstance(obs, Capsule) else obs.capsules
        if idx < 4:
            boundary_caps.extend(sub_caps)
        else:
            internal_caps.extend(sub_caps)

    # Perimeter wall centerline is at 0 and width/height with radius 0.5.
    # Internal obstacles must lie strictly inside [0.5, width - 0.5] x [0.5, height - 0.5].
    xmin, xmax = 0.5, float(width) - 0.5
    ymin, ymax = 0.5, float(height) - 0.5

    clipped_internal = []
    for c in internal_caps:
        res = liang_barsky_clip(c.x1, c.y1, c.x2, c.y2, xmin, xmax, ymin, ymax)
        if res is not None:
            clipped_internal.append(Capsule(res[0], res[1], res[2], res[3], c.r))

    capsules = boundary_caps + clipped_internal

    print(f"  Extracted {len(capsules)} continuous capsule segments (strictly clipped to arena boundary).")
    print(f"  Regular Pellets: {len(w.pellets)}, Power Pellets: {len(w.power_pellets)}")

    # ─────────────────────────────────────────────────────────────────────────
    # 1. Generate Gazebo SDF World File
    # ─────────────────────────────────────────────────────────────────────────
    sdf_lines = []
    sdf_lines.append('<?xml version="1.0" ?>')
    sdf_lines.append('<sdf version="1.6">')
    sdf_lines.append('  <world name="pacman_continuous_world">')
    sdf_lines.append('    <include><uri>model://sun</uri></include>')
    sdf_lines.append('    <include><uri>model://ground_plane</uri></include>')
    sdf_lines.append('    <physics type="ode">')
    sdf_lines.append('      <max_step_size>0.002</max_step_size>')
    sdf_lines.append('      <real_time_update_rate>500</real_time_update_rate>')
    sdf_lines.append('      <ode>')
    sdf_lines.append('        <solver>')
    sdf_lines.append('          <type>quick</type>')
    sdf_lines.append('          <iters>50</iters>')
    sdf_lines.append('          <sor>1.3</sor>')
    sdf_lines.append('        </solver>')
    sdf_lines.append('        <constraints>')
    sdf_lines.append('          <cfm>0.00001</cfm>')
    sdf_lines.append('          <erp>0.2</erp>')
    sdf_lines.append('          <contact_max_correcting_vel>0.5</contact_max_correcting_vel>')
    sdf_lines.append('          <contact_surface_layer>0.001</contact_surface_layer>')
    sdf_lines.append('        </constraints>')
    sdf_lines.append('      </ode>')
    sdf_lines.append('    </physics>')
    sdf_lines.append('    <plugin name="gazebo_ros_state" filename="libgazebo_ros_state.so">')
    sdf_lines.append('      <ros><namespace>/</namespace></ros>')
    sdf_lines.append('    </plugin>')

    # Model: Arena Walls
    sdf_lines.append('    <model name="arena_walls">')
    sdf_lines.append('      <static>true</static>')
    sdf_lines.append('      <pose>0 0 0 0 0 0</pose>')

    for idx, c in enumerate(capsules):
        wx1, wy1 = to_world(c.x1, c.y1)
        wx2, wy2 = to_world(c.x2, c.y2)
        r_world = c.r * scale
        dx = wx2 - wx1
        dy = wy2 - wy1
        length = math.hypot(dx, dy)
        cx = (wx1 + wx2) / 2.0
        cy = (wy1 + wy2) / 2.0
        yaw = math.atan2(dy, dx)
        hz = wall_height / 2.0

        # Trunk box link
        sdf_lines.append(f'      <link name="wall_box_{idx}">')
        sdf_lines.append(f'        <pose>{cx:.4f} {cy:.4f} {hz:.4f} 0 0 {yaw:.4f}</pose>')
        sdf_lines.append(f'        <collision name="col">')
        sdf_lines.append(f'          <geometry><box><size>{length:.4f} {r_world*2:.4f} {wall_height:.4f}</size></box></geometry>')
        sdf_lines.append(f'          <surface><friction><ode><mu>0.01</mu><mu2>0.01</mu2></ode></friction></surface>')
        sdf_lines.append(f'        </collision>')
        sdf_lines.append(f'        <visual name="vis">')
        sdf_lines.append(f'          <geometry><box><size>{length:.4f} {r_world*2:.4f} {wall_height:.4f}</size></box></geometry>')
        sdf_lines.append(f'          <material><ambient>0.1 0.1 0.45 1</ambient><diffuse>0.1 0.1 0.6 1</diffuse></material>')
        sdf_lines.append(f'        </visual>')
        sdf_lines.append(f'      </link>')

        # Cylinder endcap 1
        sdf_lines.append(f'      <link name="wall_cap1_{idx}">')
        sdf_lines.append(f'        <pose>{wx1:.4f} {wy1:.4f} {hz:.4f} 0 0 0</pose>')
        sdf_lines.append(f'        <collision name="col">')
        sdf_lines.append(f'          <geometry><cylinder><radius>{r_world:.4f}</radius><length>{wall_height:.4f}</length></cylinder></geometry>')
        sdf_lines.append(f'          <surface><friction><ode><mu>0.01</mu><mu2>0.01</mu2></ode></friction></surface>')
        sdf_lines.append(f'        </collision>')
        sdf_lines.append(f'        <visual name="vis">')
        sdf_lines.append(f'          <geometry><cylinder><radius>{r_world:.4f}</radius><length>{wall_height:.4f}</length></cylinder></geometry>')
        sdf_lines.append(f'          <material><ambient>0.1 0.1 0.45 1</ambient><diffuse>0.1 0.1 0.6 1</diffuse></material>')
        sdf_lines.append(f'        </visual>')
        sdf_lines.append(f'      </link>')

        # Cylinder endcap 2
        sdf_lines.append(f'      <link name="wall_cap2_{idx}">')
        sdf_lines.append(f'        <pose>{wx2:.4f} {wy2:.4f} {hz:.4f} 0 0 0</pose>')
        sdf_lines.append(f'        <collision name="col">')
        sdf_lines.append(f'          <geometry><cylinder><radius>{r_world:.4f}</radius><length>{wall_height:.4f}</length></cylinder></geometry>')
        sdf_lines.append(f'          <surface><friction><ode><mu>0.01</mu><mu2>0.01</mu2></ode></friction></surface>')
        sdf_lines.append(f'        </collision>')
        sdf_lines.append(f'        <visual name="vis">')
        sdf_lines.append(f'          <geometry><cylinder><radius>{r_world:.4f}</radius><length>{wall_height:.4f}</length></cylinder></geometry>')
        sdf_lines.append(f'          <material><ambient>0.1 0.1 0.45 1</ambient><diffuse>0.1 0.1 0.6 1</diffuse></material>')
        sdf_lines.append(f'        </visual>')
        sdf_lines.append(f'      </link>')

    sdf_lines.append('    </model>')

    # Regular Pellets: Emissive white floating spheres (purely visual pickups)
    pellet_z = 0.36
    pellet_r = 0.05
    for p_idx, p in enumerate(w.pellets):
        wx, wy = to_world(p[0], p[1])
        sdf_lines.append(f'    <model name="pellet_{p_idx}">')
        sdf_lines.append('      <static>true</static>')
        sdf_lines.append(f'      <pose>{wx:.4f} {wy:.4f} {pellet_z:.4f} 0 0 0</pose>')
        sdf_lines.append('      <link name="link">')
        sdf_lines.append('        <visual name="vis">')
        sdf_lines.append(f'          <geometry><sphere><radius>{pellet_r:.4f}</radius></sphere></geometry>')
        sdf_lines.append('          <material>')
        sdf_lines.append('            <ambient>0.9 0.9 0.9 1</ambient>')
        sdf_lines.append('            <diffuse>0.9 0.9 0.9 1</diffuse>')
        sdf_lines.append('            <emissive>0.7 0.7 0.7 1</emissive>')
        sdf_lines.append('          </material>')
        sdf_lines.append('        </visual>')
        sdf_lines.append('      </link>')
        sdf_lines.append('    </model>')

    # Power Pellets: Emissive golden floating spheres (purely visual pickups)
    power_z = 0.38
    power_r = 0.10
    for pp_idx, pp in enumerate(w.power_pellets):
        wx, wy = to_world(pp[0], pp[1])
        sdf_lines.append(f'    <model name="power_{pp_idx}">')
        sdf_lines.append('      <static>true</static>')
        sdf_lines.append(f'      <pose>{wx:.4f} {wy:.4f} {power_z:.4f} 0 0 0</pose>')
        sdf_lines.append('      <link name="link">')
        sdf_lines.append('        <visual name="vis">')
        sdf_lines.append(f'          <geometry><sphere><radius>{power_r:.4f}</radius></sphere></geometry>')
        sdf_lines.append('          <material>')
        sdf_lines.append('            <ambient>1.0 0.84 0.0 1</ambient>')
        sdf_lines.append('            <diffuse>1.0 0.84 0.0 1</diffuse>')
        sdf_lines.append('            <emissive>0.8 0.65 0.0 1</emissive>')
        sdf_lines.append('          </material>')
        sdf_lines.append('        </visual>')
        sdf_lines.append('      </link>')
        sdf_lines.append('    </model>')

    sdf_lines.append('  </world>')
    sdf_lines.append('</sdf>')

    world_sdf_path = os.path.join(out_dir, f"pacman_continuous_stage_{stage_idx}.world")
    with open(world_sdf_path, "w") as f:
        f.write("\n".join(sdf_lines))
    print(f"  [Output] Gazebo World saved to: {world_sdf_path}")

    # ─────────────────────────────────────────────────────────────────────────
    # 2. Generate Native MuJoCo MJCF XML File (Zero sim-to-sim gap)
    # ─────────────────────────────────────────────────────────────────────────
    mjcf_lines = []
    mjcf_lines.append(f'<mujoco model="pacman_stage_{stage_idx}">')
    mjcf_lines.append('  <compiler angle="radian" autolimits="true"/>')
    mjcf_lines.append('  <option timestep="0.002" gravity="0 0 -9.81"/>')
    mjcf_lines.append('  <asset>')
    mjcf_lines.append('    <material name="wall_mat" rgba="0.1 0.1 0.6 1"/>')
    mjcf_lines.append('    <material name="pellet_mat" rgba="0.9 0.9 0.9 1"/>')
    mjcf_lines.append('    <material name="power_mat" rgba="1.0 0.84 0.0 1"/>')
    mjcf_lines.append('    <material name="floor_mat" rgba="0.2 0.2 0.2 1"/>')
    mjcf_lines.append('  </asset>')
    mjcf_lines.append('  <worldbody>')
    mjcf_lines.append(f'    <geom name="floor" type="plane" size="{width*scale} {height*scale} 0.1" material="floor_mat"/>')
    mjcf_lines.append('    <light diffuse="0.8 0.8 0.8" pos="0 0 10" dir="0 0 -1"/>')

    # MuJoCo natively supports horizontal capsule primitives!
    hz = wall_height / 2.0
    for idx, c in enumerate(capsules):
        wx1, wy1 = to_world(c.x1, c.y1)
        wx2, wy2 = to_world(c.x2, c.y2)
        r_world = c.r * scale
        mjcf_lines.append(
            f'    <geom name="capsule_wall_{idx}" type="capsule" '
            f'fromto="{wx1:.4f} {wy1:.4f} {hz:.4f} {wx2:.4f} {wy2:.4f} {hz:.4f}" '
            f'size="{r_world:.4f}" material="wall_mat"/>'
        )

    # Pellets as site markers or non-colliding visual geoms
    for p_idx, p in enumerate(w.pellets):
        wx, wy = to_world(p[0], p[1])
        mjcf_lines.append(
            f'    <geom name="pellet_{p_idx}" type="sphere" pos="{wx:.4f} {wy:.4f} {pellet_z:.4f}" '
            f'size="{pellet_r:.4f}" material="pellet_mat" contype="0" conaffinity="0"/>'
        )
    for pp_idx, pp in enumerate(w.power_pellets):
        wx, wy = to_world(pp[0], pp[1])
        mjcf_lines.append(
            f'    <geom name="power_{pp_idx}" type="sphere" pos="{wx:.4f} {wy:.4f} {power_z:.4f}" '
            f'size="{power_r:.4f}" material="power_mat" contype="0" conaffinity="0"/>'
        )

    mjcf_lines.append('  </worldbody>')
    mjcf_lines.append('</mujoco>')

    mjcf_path = os.path.join(out_dir, f"pacman_continuous_stage_{stage_idx}.xml")
    with open(mjcf_path, "w") as f:
        f.write("\n".join(mjcf_lines))
    print(f"  [Output] MuJoCo MJCF saved to: {mjcf_path}")

    # ─────────────────────────────────────────────────────────────────────────
    # 3. Export Arena Metadata JSON (For ROS 2 Agent Nodes)
    # ─────────────────────────────────────────────────────────────────────────
    # Compute open spawn points for Pacman and ghosts with generous clearance (>= 1.0m obstacle, >= 2.2m perimeter)
    candidate_pts = getattr(w, 'safe_area', [])
    if candidate_pts:
        c_arr = np.array(candidate_pts)
        dist_sq, r_seg = w._points_to_segments_dist_sq(c_arr[:, 0], c_arr[:, 1])
        obs_clearance = (np.sqrt(dist_sq) - r_seg) * scale
        min_obs_c = np.min(obs_clearance, axis=1) if obs_clearance.shape[1] > 0 else np.full(len(c_arr), 999.0)
        bound_clearance = np.minimum.reduce([
            c_arr[:, 0] * scale,
            (width - c_arr[:, 0]) * scale,
            c_arr[:, 1] * scale,
            (height - c_arr[:, 1]) * scale
        ]) - 0.5 * scale
        # Filter for points with at least 1.0m obstacle clearance AND at least 2.2m from outer walls
        valid_indices = np.where((min_obs_c >= 1.0) & (bound_clearance >= 2.2))[0]
        if len(valid_indices) < n_ghosts + 1:
            valid_indices = np.where((min_obs_c >= 0.80) & (bound_clearance >= 1.8))[0]
        safe_pts = [to_world(candidate_pts[i][0], candidate_pts[i][1]) for i in valid_indices]
    else:
        safe_pts = []

    if not safe_pts:
        # Fallback to random passable samples
        for _ in range(100):
            rx = np.random.uniform(3, width - 3)
            ry = np.random.uniform(3, height - 3)
            if w.is_passable(rx, ry, radius=0.45):
                safe_pts.append(to_world(rx, ry))

    pacman_start = safe_pts[0] if safe_pts else (0.0, 0.0)

    # Compute well-separated ghost spawn points
    ghost_starts = []
    available = list(safe_pts[1:])
    for _ in range(n_ghosts):
        if not available:
            ghost_starts.append((-pacman_start[0], -pacman_start[1]))
            continue
        # Pick point furthest from pacman and already chosen ghosts
        def dist_score(pt):
            d_pac = math.hypot(pt[0] - pacman_start[0], pt[1] - pacman_start[1])
            d_gh = min([math.hypot(pt[0] - gs[0], pt[1] - gs[1]) for gs in ghost_starts], default=999.0)
            return min(d_pac, d_gh)
        best_idx = int(np.argmax([dist_score(p) for p in available]))
        ghost_starts.append(available.pop(best_idx))

    # Filter PRM nodes for safe corridor clearance
    raw_nodes = getattr(w, 'prm_nodes', [])
    if raw_nodes:
        nodes_xy = np.array([(n[1], n[0]) for n in raw_nodes])
        dist_sq, r_seg = w._points_to_segments_dist_sq(nodes_xy[:, 0], nodes_xy[:, 1])
        obs_c = (np.sqrt(dist_sq) - r_seg) * scale
        min_prm_obs = np.min(obs_c, axis=1) if obs_c.shape[1] > 0 else np.full(len(nodes_xy), 999.0)
        bound_prm = np.minimum.reduce([
            nodes_xy[:, 0] * scale,
            (width - nodes_xy[:, 0]) * scale,
            nodes_xy[:, 1] * scale,
            (height - nodes_xy[:, 1]) * scale
        ]) - 0.5 * scale
        valid_prm_mask = (min_prm_obs >= 0.70) & (bound_prm >= 1.5)
        filtered_raw_nodes = [n for i, n in enumerate(raw_nodes) if valid_prm_mask[i]]
    else:
        filtered_raw_nodes = []

    # Build PRM adjacency list on filtered nodes
    old_to_new = {n: i for i, n in enumerate(filtered_raw_nodes)}
    prm_adj = []
    prm_graph = getattr(w, 'prm_graph', {})
    for n in filtered_raw_nodes:
        nbrs = prm_graph.get(n, [])
        valid_nbr_indices = [old_to_new[nbr[1]] for nbr in nbrs if len(nbr) > 1 and nbr[1] in old_to_new]
        prm_adj.append(valid_nbr_indices)

    filtered_world_nodes = [list(to_world(node[1], node[0])) for node in filtered_raw_nodes]

    metadata = {
        "stage": stage_idx,
        "scale": scale,
        "width_m": width * scale,
        "height_m": height * scale,
        "wall_height_m": wall_height,
        "n_ghosts": n_ghosts,
        "n_power": n_power,
        "pacman_start": pacman_start,
        "ghost_starts": ghost_starts,
        "pellets": [list(to_world(p[0], p[1])) for p in w.pellets],
        "power_pellets": [list(to_world(pp[0], pp[1])) for pp in w.power_pellets],
        "prm_nodes": filtered_world_nodes,
        "prm_adjacency": prm_adj,
        "radio_comm_radius_m": 12.0 * scale,
        "lidar_max_range_m": 10.0 * scale,
        "tactical_envelope_m": 6.0 * scale,
        "pickup_distance_m": 0.55,
        "kill_distance_m": 0.50,
    }

    metadata_path = os.path.join(out_dir, f"arena_metadata_stage_{stage_idx}.json")
    with open(metadata_path, "w") as f:
        json.dump(metadata, f, indent=2)
    print(f"  [Output] Arena Metadata saved to: {metadata_path}")
    print("=== Arena Generation Complete ===")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate Continuous Arena for Pacmanbot Gazebo / MuJoCo")
    parser.add_argument("--stage", type=int, default=1, help="Curriculum stage index (1 to 4)")
    parser.add_argument("--scale", type=float, default=1.5, help="Scale factor in meters per unit (default: 1.5)")
    parser.add_argument("--wall-height", type=float, default=0.75, help="Wall height in meters (default: 0.75)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    parser.add_argument("--out-dir", type=str, default=None, help="Output directory")
    args = parser.parse_args()

    generate_and_export(
        stage_idx=args.stage,
        scale=args.scale,
        wall_height=args.wall_height,
        out_dir=args.out_dir,
        seed=args.seed
    )
